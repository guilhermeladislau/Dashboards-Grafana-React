/**
 * Obtém o tipo de dispositivo ativo considerando a opção nova ou mapeando o legado
 */
export function obterDispositivoAtivo(opcoes?: Partial<PanelOptions>): DeviceType {
  if (opcoes?.deviceType && opcoes.deviceType !== 'auto') {
    return opcoes.deviceType;
  }
  // Compatibilidade com configurações antigas
  switch (opcoes?.panelType) {
    case 'firewall':
      return 'firewall';
    case 'vmware':
      return 'vm';
    case 'disk':
    case 'cpu':
    case 'memory':
    case 'system':
      return 'servidor';
    case 'network':
      return 'porta_rede';
    default:
      return 'auto';
  }
}

/**
 * Retorna a métrica específica selecionada para o dispositivo ativo
 */
export function obterMetricaDispositivoAtiva(
  opcoes?: Partial<PanelOptions>
): AnyDeviceMetricType | null {
  const dispositivo = obterDispositivoAtivo(opcoes);

  switch (dispositivo) {
    case 'firewall': {
      const m = opcoes?.firewallMetric || opcoes?.firewallMetricType || 'auto_device';
      return m === 'auto_device' ? null : m;
    }
    case 'vm': {
      const m = opcoes?.vmMetric || opcoes?.vmwareMetricType || 'auto_device';
      return m === 'auto_device' ? null : m;
    }
    case 'proxy': {
      const m = opcoes?.proxyMetric || 'auto_device';
      return m === 'auto_device' ? null : m;
    }
    case 'host': {
      const m = opcoes?.hostMetric || 'auto_device';
      return m === 'auto_device' ? null : m;
    }
    case 'servidor': {
      const m = opcoes?.servidorMetric || 'auto_device';
      return m === 'auto_device' ? null : m;
    }
    case 'access_point': {
      const m = opcoes?.accessPointMetric || 'auto_device';
      return m === 'auto_device' ? null : m;
    }
    case 'porta_rede': {
      const m = opcoes?.portaRedeMetric || 'auto_device';
      return m === 'auto_device' ? null : m;
    }
    case 'auto':
    default:
      return null;
  }
}
